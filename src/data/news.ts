export type NewsItem = {
  /** YYYY-MM-DD */
  date: string;
  title: string;
  /** URLになる。/news/<slug>/ で詳細ページが出る。英小文字とハイフンだけ */
  slug: string;
  category?: string;
  /** 一覧では出さない。詳細ページの冒頭と、検索結果の説明文に使う1〜2文 */
  lead: string;
  /** 本文。配列のひとつが1段落。無ければ lead だけの短い報告になる */
  body?: string[];
  /** サイト内の関連ページ。詳細ページの末尾に出す */
  related?: { label: string; href: string }[];
  /** 外部記事へのリンク。掲載メディアの記事などに使う */
  href?: string;
  /** リンク先の媒体名。href があるときだけ表示する */
  source?: string;
};

