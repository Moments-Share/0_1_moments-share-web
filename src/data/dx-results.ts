/* ============================================================
   DX・AX支援の実績の数字。/service-dx/ の事例の節の先頭に並ぶ。
   空のあいだは、その行ごと出ない。

   書き方の約束：
   ・必ず実測値にする。見込みや目標は載せない。
   ・単位は value に含めず unit に分ける（数字だけ大きく出すため）。
   ・数えた範囲が分かるように note を付ける。
     「2025年11月〜」のように、いつからの数字かが分かる形にする。
   ============================================================ */

export type DxResult = {
  /** 数字の部分だけ。「7」「80」など */
  value: string;
  /** 単位。「件」「%」「社」など */
  unit: string;
  /** 何の数字か。10字程度 */
  label: string;
  /** 数えた範囲や条件。任意 */
  note?: string;
};

export const dxResults: DxResult[] = [];
